#!/usr/bin/env bash
# Step B — PRE-MERGE PREVIEW. Not the default pin.
#
# Builds and dry-runs the cranker against the wrapper's draft re-pin stack
# (prog #452 → #454 → #456, head branch `fix/repin-launch-fixes`) with the
# engine path-patched to master `68859b94` (the 2026-10-27 launch-fix merge
# batch). This is how #456 itself was validated. Everything lives under
# `.preview/` (gitignored) so the default build (`repo-prog` @ 5cb331dd,
# engine 4db11a8c) is never touched.
#
# Read-only against upstream: only `git fetch` + local worktrees.
#
# Usage (validator must already be up, e.g. after ./scripts/m1_bringup.sh):
#   ./scripts/preview_launch_fixes.sh                  # build + deploy + 3 cycles
#   CRANKER_SCENARIO=live_shaped ./scripts/preview_launch_fixes.sh
#
# Env:
#   PREVIEW_PROG_REF   (default origin/fix/repin-launch-fixes)
#   PREVIEW_ENGINE_REV (default 68859b94c…)
#   CRANKER_CYCLES     (default 3)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
# shellcheck disable=SC1091
source "$SCRIPT_DIR/env.sh"

PREVIEW_PROG_REF="${PREVIEW_PROG_REF:-origin/fix/repin-launch-fixes}"
PREVIEW_ENGINE_REV="${PREVIEW_ENGINE_REV:-68859b94}"
PV="$REPO_ROOT/.preview"
ENGINE_GIT="https://github.com/aeyakovenko/percolator"

mkdir -p "$PV"
git -C "$REPO_ROOT/repo-prog" fetch -q origin
git -C "$REPO_ROOT/repo" fetch -q origin

# Worktrees: .preview/repo-prog (wrapper #456 head), .preview/repo (engine).
if [ ! -d "$PV/repo-prog" ]; then
  git -C "$REPO_ROOT/repo-prog" worktree add -q --detach "$PV/repo-prog" "$PREVIEW_PROG_REF"
else
  git -C "$PV/repo-prog" checkout -q --detach "$PREVIEW_PROG_REF"
fi
if [ ! -d "$PV/repo" ]; then
  git -C "$REPO_ROOT/repo" worktree add -q --detach "$PV/repo" "$PREVIEW_ENGINE_REV"
else
  git -C "$PV/repo" checkout -q --detach "$PREVIEW_ENGINE_REV"
fi
PROG_SHA="$(git -C "$PV/repo-prog" rev-parse HEAD)"
ENGINE_SHA="$(git -C "$PV/repo" rev-parse HEAD)"
echo "==> PRE-MERGE PREVIEW: wrapper $PROG_SHA ($PREVIEW_PROG_REF) + engine $ENGINE_SHA (path patch)"

write_patch() {
  mkdir -p "$1/.cargo"
  cat > "$1/.cargo/config.toml" <<EOF
# Generated by scripts/preview_launch_fixes.sh — PRE-MERGE PREVIEW ONLY.
[patch."$ENGINE_GIT"]
percolator = { path = "$PV/repo" }
EOF
}

# Wrapper SBF build with the engine patch (config-file [patch]; cwd-scoped).
write_patch "$PV/repo-prog"
( cd "$PV/repo-prog" && cargo build-sbf --tools-version v1.52 )

# Cranker copy whose `../repo-prog` path dep resolves to the preview wrapper.
rsync -a --delete --exclude target "$REPO_ROOT/cranker/" "$PV/cranker/"
write_patch "$PV/cranker"
( cd "$PV/cranker" && cargo update -q -p percolator 2>/dev/null || true )

KP="$PV/repo-prog/target/deploy/percolator_prog-keypair.json"
SO="$PV/repo-prog/target/deploy/percolator_prog.so"
PROG_ID="$(solana-keygen pubkey "$KP")"
echo "==> deploying preview program $PROG_ID"
solana program deploy "$SO" --program-id "$KP" >/dev/null

echo "==> cranker (preview) CRANKER_CYCLES=${CRANKER_CYCLES:-3}"
cd "$PV/cranker"
if [ "${CRANKER_SCENARIO:-}" = "live_shaped" ]; then
  PERCOLATOR_PROGRAM_ID="$PROG_ID" CRANKER_PREVIEW_LABEL="pre-merge preview" \
    cargo run --release --bin live_shaped
else
  PERCOLATOR_PROGRAM_ID="$PROG_ID" CRANKER_CYCLES="${CRANKER_CYCLES:-3}" \
    cargo run --release --bin cranker
fi
